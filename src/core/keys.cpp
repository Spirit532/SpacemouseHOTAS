const int kKeyCount = sizeof(kKeys) / sizeof(kKeys[0]);

const KeyDef* keyByVk(int vk) {
    for (int i = 0; i < kKeyCount; i++)
        if (kKeys[i].vk == vk) return &kKeys[i];
    return nullptr;
}

const KeyDef* keyByX11Keysym(uint32_t keysym) {
    if (keysym >= 'A' && keysym <= 'Z') keysym += 'a' - 'A';
    for (int i = 0; i < kKeyCount; i++)
        if (kKeys[i].x11Keysym == keysym) return &kKeys[i];
    return nullptr;
}

const KeyDef* keyByMacKeyCode(int keyCode) {
    for (int i = 0; i < kKeyCount; i++)
        if (kKeys[i].macKey == keyCode) return &kKeys[i];
    return nullptr;
}

const char* mouseButtonName(int button) {
    static const char* const kNames[MOUSE_BUTTON_COUNT] = {"Mouse L", "Mouse R", "Mouse M", "Mouse X1", "Mouse X2"};
    return button >= 0 && button < MOUSE_BUTTON_COUNT ? kNames[button] : "?";
}
